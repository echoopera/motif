#!/usr/bin/env python3
# Regenerates sdk/motif-kit-sdk/lib/kit-gl.js from the app build: python3 build/sdk_sync.py Motif.html sdk/motif-kit-sdk/lib/kit-gl.js
import sys
h = open(sys.argv[1], encoding='utf-8').read().split('\n')
def mod(name):
    i = next(k for k, l in enumerate(h) if l.startswith('// ---- module: ' + name))
    j = next(k for k in range(i + 1, len(h)) if h[k].startswith('// ---- module: '))
    return '\n'.join(h[i:j]).rstrip('\n') + '\n'
head = ('// GENERATED by build/sdk_sync.py from the app build (kit-gl, kit-v4, kit-sandbox, text-atlas modules). Do not edit.\n'
        '// DOM-free validation (motif-kit@1 to @4, static GLSL analysis) + the WebGL2 kit runtime + the text-input atlas rasterizer + the\n'
        '// motif-kit@4 toolkit (vector baker, playhead, sequences), as the app runs them. textAtlas and v4 draw on OffscreenCanvas (browser only).\n')
body = '\n'.join(mod(n) for n in ['kit-gl', 'kit-v4', 'kit-sandbox', 'text-atlas'])
tail = '\nreturn Object.assign({}, __m_kit_gl, __m_kit_sandbox, { textAtlas: __m_text_atlas, v4: __m_kit_v4, validateKit: __m_kit_sandbox.validate, validateKitV1: __m_kit_gl.validateKit, KIT_FORMAT: __m_kit_sandbox.KIT_FORMAT_4 });\n'
open(sys.argv[2], 'w', encoding='utf-8').write(head + body + tail)
print('wrote', sys.argv[2])
