// Generates schemas/motif-kit-3.schema.json (motif-kit@3, reads @1 and @2) from the hand-written motif-kit@2 schema plus the
// text-input rules in src-v5/modules/04-kit-gl.js (KG.TEXT), so limits in the schema cannot drift from the validator.
//   node tools/gen-kit-schema.mjs           write the schema
//   node tools/gen-kit-schema.mjs --check   fail if the committed schema is stale (used by tests)
import fs from 'node:fs'; import path from 'node:path';
import { load } from '../tests/load.mjs';
const root = path.resolve(import.meta.dirname, '..');
const out = path.join(root, 'schemas/motif-kit-3.schema.json');
const KG = load('kit-gl').__m_kit_gl, TX = KG.TEXT;
const s = JSON.parse(fs.readFileSync(path.join(root, 'schemas/motif-kit-2.schema.json'), 'utf8'));
s.$id = 'https://motif.local/schemas/motif-kit-3.schema.json';
s.$comment = 'GENERATED by tools/gen-kit-schema.mjs from schemas/motif-kit-2.schema.json and the text-input rules in src-v5/modules/04-kit-gl.js. Do not edit by hand.';
s.title = 'Motif kit manifest (motif-kit@3, reads motif-kit@1 and motif-kit@2)';
s.description = s.description.replace('motif-kit@2 is a superset of motif-kit@1', 'motif-kit@3 adds text inputs and the "text" capability to motif-kit@2, which is a superset of motif-kit@1')
  + ' Text inputs (motif-kit@3 only): inputs[].type "text" declares 1–3 lines the host rasterizes into ONE atlas texture; strings never become GLSL uniforms (see sdk/motif-kit-sdk/docs/text-inputs.md).';
s.properties.format = { enum: ['motif-kit@1', 'motif-kit@2', 'motif-kit@3'] };
s.properties.capabilities.items.enum = ['media', 'audio', 'feedback', 'text'];
s.properties.capabilities.description = 'motif-kit@2 and @3. Declared access the user approves at install ("text": @3 only, local font rasterization of text typed into the layer). Kits can never request network, DOM or script access.';
// Inputs: media (as @2) or text (@3).
const media = s.$defs.inputs.items;
const family = { type: 'string', minLength: 1, maxLength: TX.family, pattern: KG.FAMILY_RE.source.replace(/^\^\[/, '^[').replace('\\p{L}\\p{N}', '\\p{L}\\p{N}') };
const textLine = {
  type: 'object', required: ['id'], additionalProperties: false,
  properties: {
    id: { type: 'string', pattern: KG.LINE_ID_RE.source }, label: { type: 'string' },
    def: { type: 'string', maxLength: TX.chars, pattern: '^[^\\u0000-\\u001F\\u007F-\\u009F\\u2028\\u2029]*$', description: 'Default text: one line, no control characters, at most maxLength.' },
    maxLength: { type: 'integer', minimum: 1, maximum: TX.chars, default: TX.defChars },
    font: { type: 'object', additionalProperties: false, properties: { family: family, weight: { enum: TX.weights } }, description: 'Default font. Fonts are never loaded from a kit: the family is looked up on the device, with a fallback.' },
    size: { type: 'number', minimum: TX.size[0], maximum: TX.size[1], default: TX.defSize, description: 'Em size as a fraction of the band height.' },
    tracking: { type: 'number', minimum: TX.tracking[0], maximum: TX.tracking[1], default: TX.defTracking, description: 'Extra letter spacing in em.' },
    align: { enum: TX.aligns, default: 'center' },
  },
};
const text = {
  type: 'object', required: ['id', 'type', 'lines'], additionalProperties: false,
  properties: {
    id: media.properties.id, type: { const: 'text' }, label: { type: 'string' }, hint: { type: 'string' },
    aspect: { type: 'number', minimum: TX.aspect[0], maximum: TX.aspect[1], default: TX.defAspect, description: 'Band width : height of every line in the atlas.' },
    lines: { type: 'array', minItems: 1, maxItems: TX.lines, items: textLine },
  },
};
s.$defs.mediaInput = media; s.$defs.textInput = text; s.$defs.textLine = textLine;
s.$defs.inputs = { type: 'array', maxItems: 2, items: { if: { required: ['type'], properties: { type: { const: 'text' } } }, then: { $ref: '#/$defs/textInput' }, else: { $ref: '#/$defs/mediaInput' } } };
// Text inputs and the text capability need motif-kit@3.
const noText = { not: { anyOf: [
  { required: ['capabilities'], properties: { capabilities: { type: 'array', contains: { const: 'text' } } } },
  { required: ['inputs'], properties: { inputs: { type: 'array', contains: { required: ['type'], properties: { type: { const: 'text' } } } } } },
  { required: ['styles'], properties: { styles: { type: 'array', contains: { required: ['inputs'], properties: { inputs: { type: 'array', contains: { required: ['type'], properties: { type: { const: 'text' } } } } } } } } },
] } };
s.allOf.push({ if: { not: { properties: { format: { const: 'motif-kit@3' } } } }, then: noText });
const v2rule = s.allOf.find(r => r.if && r.if.properties && r.if.properties.format && r.if.properties.format.const === 'motif-kit@2');
s.allOf.push({ if: { properties: { format: { const: 'motif-kit@3' } } }, then: v2rule.then });
const textOut = JSON.stringify(s, null, 1) + '\n';
if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== textOut) { console.error('schemas/motif-kit-3.schema.json is stale: run node tools/gen-kit-schema.mjs'); process.exit(1); }
  console.log('motif-kit-3.schema.json up to date');
} else { fs.writeFileSync(out, textOut); console.log(`wrote ${path.relative(root, out)}`); }
